module ElmDeviceDataMod
  !
  ! GENERATED by `spel device-data` from the elm_drv analysis of the sources
  ! (/global/u2/p/pschwar3/merge/E3SM, d1a0069e2d). Do not edit; regenerate.
  !
  ! Device data layer for full-model OpenACC runs: device initialization, the
  ! one-time deep copy of every type instance to the device (first time step),
  ! and whole-state updates around the host-side sections of the driver. The
  ! per-type routines are in the DeepCopy*Mod group modules.
  ! Everything is a no-op without _OPENACC.
  !
#ifdef _OPENACC
  use openacc
#endif
  use elm_varctl, only : iulog
  use spmdMod,    only : masterproc, iam
  use DeepCopyParamsMod, only : params_copyin, params_attach, params_check, params_update
  use DeepCopySubgridMod, only : subgrid_copyin, subgrid_attach, subgrid_check, subgrid_update
  use DeepCopyCouplingMod, only : coupling_copyin, coupling_attach, coupling_check, coupling_update
  use DeepCopyBiogeophysMod, only : biogeophys_copyin, biogeophys_attach, biogeophys_check, biogeophys_update
  use DeepCopyVegNutrientMod, only : veg_nutrient_copyin, veg_nutrient_attach, veg_nutrient_check, veg_nutrient_update
  use DeepCopySoilNutrientMod, only : soil_nutrient_copyin, soil_nutrient_attach, soil_nutrient_check, soil_nutrient_update
  use DeepCopyGlobalsMod, only : globals_copyin, globals_update
  implicit none
  private
  public :: elm_device_init, elm_device_copyin, elm_device_update, elm_device_resident
  logical, save :: elm_device_resident = .false.  ! the state lives on the device (public above)
contains

  subroutine elm_device_init()
    ! Select the device and initialize the runtime; called first in initialize1.
    ! Data in `declare` directives was placed on the default device when the
    ! program started, so each rank must see exactly one device (srun
    ! --gpus-per-task=1); with several visible devices the local rank picks one
    ! and the declared module data of the other device is lost: warn loudly.
#ifdef _OPENACC
    integer :: ndev, dev, localid, ios
    character(len=32) :: s
    ndev = acc_get_num_devices(acc_device_nvidia)
    if (ndev > 1) then
       call get_environment_variable('SLURM_LOCALID', s, status=ios)
       localid = 0
       if (ios == 0) read(s, *, iostat=ios) localid
       dev = mod(max(localid, 0), ndev)
       call acc_set_device_num(dev, acc_device_nvidia)
       write(iulog,*) 'elm_device_init: WARNING rank', iam, 'sees', ndev, 'devices; picked', dev, &
            ' - module data in acc declare directives may be on another device; bind one GPU per rank'
    end if
    call acc_init(acc_device_nvidia)
    if (masterproc .or. ndev > 1) write(iulog,*) 'elm_device_init: rank', iam, 'device', &
         acc_get_device_num(acc_device_nvidia), 'of', ndev
#endif
  end subroutine elm_device_init

  subroutine elm_device_copyin()
    ! One-time deep copy of every type instance, then the alias attachments
    ! (their targets may be in other groups) and the presence check.
#ifdef _OPENACC
    integer :: nmiss
    if (elm_device_resident) return
    call globals_copyin()
    call params_copyin()
    call subgrid_copyin()
    call coupling_copyin()
    call biogeophys_copyin()
    call veg_nutrient_copyin()
    call soil_nutrient_copyin()
    call params_attach()
    call subgrid_attach()
    call coupling_attach()
    call biogeophys_attach()
    call veg_nutrient_attach()
    call soil_nutrient_attach()
    nmiss = 0
    call params_check(nmiss)
    call subgrid_check(nmiss)
    call coupling_check(nmiss)
    call biogeophys_check(nmiss)
    call veg_nutrient_check(nmiss)
    call soil_nutrient_check(nmiss)
    if (nmiss > 0) then
       write(iulog,*) 'elm_device_copyin: rank', iam, ':', nmiss, 'arrays NOT present on the device'
    else if (masterproc) then
       write(iulog,*) 'elm_device_copyin: every array of every instance is present on the device'
    end if
    elm_device_resident = .true.
#endif
  end subroutine elm_device_copyin

  subroutine elm_device_update(to_device)
    ! update device (host -> device) or update self (device -> host) of the whole state.
    logical, intent(in) :: to_device
#ifdef _OPENACC
    if (.not. elm_device_resident) return
    call globals_update(to_device)
    call params_update(to_device)
    call subgrid_update(to_device)
    call coupling_update(to_device)
    call biogeophys_update(to_device)
    call veg_nutrient_update(to_device)
    call soil_nutrient_update(to_device)
#endif
  end subroutine elm_device_update

end module ElmDeviceDataMod
